export const FileManagerView: React.FC<FileManagerViewProps> = ({
  server,
  onSaveConfigFile,
  onNotify
}) => {
  const [files, setFiles] = useState<ServerFileItem[]>(() => getInitialFiles(server));
  const [currentPath, setCurrentPath] = useState<string>('/');
  const [selectedFile, setSelectedFile] = useState<ServerFileItem | null>(null);
  const [editorContent, setEditorContent] = useState<string>('');
  const [searchFilter, setSearchFilter] = useState('');
  const [saveSuccess, setSaveSuccess] = useState(false);
  const [copySftpSuccess, setCopySftpSuccess] = useState(false);

  // New file/folder modals
  const [isNewFileModalOpen, setIsNewFileModalOpen] = useState(false);
  const [newFileName, setNewFileName] = useState('');
  const [isUploading, setIsUploading] = useState(false);
  const [uploadProgress, setUploadProgress] = useState(0);
  const [fileToDelete, setFileToDelete] = useState<string | null>(null);

  // Current files in current directory
  const currentDirectoryFiles = useMemo(() => {
    return files.filter(f => {
      // Direct children of currentPath
      if (currentPath === '/') {
        // files with no slash other than leading
        const parts = f.path.split('/').filter(Boolean);
        return parts.length === 1;
      } else {
        return f.path.startsWith(currentPath + '/') && f.path.slice(currentPath.length + 1).split('/').length === 1;
      }
    }).filter(f => f.name.toLowerCase().includes(searchFilter.toLowerCase()));
  }, [files, currentPath, searchFilter]);

  const formatFileSize = (bytes: number) => {
    if (bytes >= 1024 * 1024 * 1024) return `${(bytes / (1024 * 1024 * 1024)).toFixed(1)} GB`;
    if (bytes >= 1024 * 1024) return `${(bytes / (1024 * 1024)).toFixed(1)} MB`;
    if (bytes >= 1024) return `${(bytes / 1024).toFixed(1)} KB`;
    return `${bytes} B`;
  };

  const handleOpenFile = (file: ServerFileItem) => {
    if (file.type === 'directory') {
      setCurrentPath(file.path);
    } else {
      setSelectedFile(file);
      setEditorContent(file.content || `# Binary oder schreibgeschützte Datei: ${file.name}`);
    }
  };

  const handleSaveFile = () => {
    if (!selectedFile) return;
    setFiles(prev => prev.map(f => f.path === selectedFile.path ? { ...f, content: editorContent, lastModified: 'Gerade eben' } : f));
    if (onSaveConfigFile) {
      onSaveConfigFile(selectedFile.name, editorContent);
    }
    setSaveSuccess(true);
    if (onNotify) onNotify(`Datei ${selectedFile.name} erfolgreich gespeichert.`);
    setTimeout(() => setSaveSuccess(false), 2500);
  };

  // 1-Click EULA Accept
  const handleAcceptEula = () => {
    const eulaFile = files.find(f => f.name === 'eula.txt');
    if (eulaFile) {
      const updatedContent = `# Minecraft Server EULA akzeptiert via ApexHost Gameserver Manager\neula=true\n`;
      setFiles(prev => prev.map(f => f.name === 'eula.txt' ? { ...f, content: updatedContent, lastModified: 'Gerade eben' } : f));
      if (selectedFile?.name === 'eula.txt') {
        setEditorContent(updatedContent);
      }
      if (onSaveConfigFile) onSaveConfigFile('eula.txt', updatedContent);
      if (onNotify) onNotify('Minecraft EULA erfolgreich mit 1 Klick akzeptiert! Server kann starten.');
    }
  };

  const eulaNeedsAccept = useMemo(() => {
    const f = files.find(file => file.name === 'eula.txt');
    return f && f.content?.includes('eula=false');
  }, [files]);

  const handleDeleteFile = (path: string) => {
    setFileToDelete(path);
  };

  const handleConfirmDeleteFile = () => {
    if (!fileToDelete) return;
    const targetPath = fileToDelete;
    setFiles(prev => prev.filter(f => !f.path.startsWith(targetPath)));
    if (selectedFile?.path === targetPath) setSelectedFile(null);
    if (onNotify) onNotify(`Datei/Ordner gelöscht: ${targetPath}`);
    setFileToDelete(null);
  };

  const handleCreateFile = () => {
    if (!newFileName.trim()) return;
    const cleanName = newFileName.trim();
    const fullPath = currentPath === '/' ? `/${cleanName}` : `${currentPath}/${cleanName}`;
    const isDir = cleanName.endsWith('/');
    const cleanDirName = isDir ? cleanName.replace(/\/$/, '') : cleanName;

    const newItem: ServerFileItem = {
      name: cleanDirName,
      path: fullPath,
      type: isDir ? 'directory' : 'file',
      sizeBytes: isDir ? 4096 : 0,
      lastModified: 'Gerade eben',
      isEditable: !isDir,
      content: isDir ? undefined : `# Neu erstellte Datei: ${cleanDirName}\n`
    };

    setFiles(prev => [...prev, newItem]);
    setIsNewFileModalOpen(false);
    setNewFileName('');
    if (onNotify) onNotify(`${isDir ? 'Ordner' : 'Datei'} "${cleanDirName}" erfolgreich angelegt.`);
  };

  const handleSimulateUpload = () => {
    setIsUploading(true);
    setUploadProgress(0);
    const interval = setInterval(() => {
      setUploadProgress(prev => {
        if (prev >= 100) {
          clearInterval(interval);
          setIsUploading(false);
          const uploadedName = `custom_addon_${Date.now().toString().slice(-4)}.jar`;
          const newItem: ServerFileItem = {
            name: uploadedName,
            path: currentPath === '/' ? `/${uploadedName}` : `${currentPath}/${uploadedName}`,
            type: 'file',
            sizeBytes: 15400000,
            lastModified: 'Gerade eben',
            isEditable: false
          };
          setFiles(p => [...p, newItem]);
          if (onNotify) onNotify(`Upload erfolgreich: ${uploadedName} (14.7 MB)`);
          return 100;
        }
        return prev + 25;
      });
    }, 200);
  };

  const sftpHost = `sftp.apexhost.net`;
  const sftpPort = 2022;
  const sftpUser = `apex_${server.id.replace(/[^a-zA-Z0-9]/g, '')}`;

  const copySftpString = () => {
    navigator.clipboard.writeText(`sftp://${sftpUser}@${sftpHost}:${sftpPort}`);
    setCopySftpSuccess(true);
    setTimeout(() => setCopySftpSuccess(false), 2000);
  };

  return (
    <div className="space-y-4">
      {/* SFTP Quick Connection Strip */}
      <div className="bg-neutral-900 border border-neutral-800 rounded-xl p-4 flex flex-col md:flex-row md:items-center justify-between gap-3 text-xs">
        <div className="flex items-center gap-3">
          <div className="p-2 bg-neutral-950 rounded-lg border border-neutral-800 text-sky-400">
            <Key className="w-4 h-4" />
          </div>
          <div>
            <div className="flex items-center gap-2">
              <span className="font-semibold text-neutral-200">SFTP / FTPS Dateizugriff</span>
              <span className="px-1.5 py-0.5 rounded text-[10px] font-mono bg-sky-950 text-sky-400 border border-sky-800/60">
                Port {sftpPort} (SSL/TLS)
              </span>
            </div>
            <p className="text-neutral-400 mt-0.5">
              Host: <span className="font-mono text-neutral-300">{sftpHost}</span> | User: <span className="font-mono text-neutral-300">{sftpUser}</span>
            </p>
          </div>
        </div>

        <div className="flex items-center gap-2">
          <button
            onClick={copySftpString}
            className="flex items-center gap-1.5 px-3 py-1.5 bg-neutral-950 hover:bg-neutral-800 text-neutral-300 rounded-lg border border-neutral-800 cursor-pointer transition-colors"
          >
            {copySftpSuccess ? <Check className="w-3.5 h-3.5 text-emerald-400" /> : <Copy className="w-3.5 h-3.5" />}
            <span>{copySftpSuccess ? 'Kopiert!' : 'SFTP-URL kopieren'}</span>
          </button>
          <a
            href={`sftp://${sftpUser}@${sftpHost}:${sftpPort}`}
            className="flex items-center gap-1.5 px-3 py-1.5 bg-sky-950 hover:bg-sky-900 text-sky-300 rounded-lg border border-sky-800/80 cursor-pointer transition-colors"
            title="In FileZilla oder WinSCP öffnen"
          >
            <ExternalLink className="w-3.5 h-3.5" />
            <span>FileZilla öffnen</span>
          </a>
        </div>
      </div>

      {/* EULA One-Click Alert Banner if Minecraft needs agreement */}
      {eulaNeedsAccept && (
        <div className="bg-amber-950/70 border border-amber-800/80 rounded-xl p-4 flex flex-col sm:flex-row sm:items-center justify-between gap-3 text-xs">
          <div className="flex items-start gap-3">
            <AlertCircle className="w-4 h-4 text-amber-400 mt-0.5 shrink-0" />
            <div>
              <div className="font-semibold text-amber-200">Minecraft EULA noch nicht akzeptiert!</div>
              <p className="text-amber-400/90 mt-0.5">
                Der Minecraft-Server kann erst starten, wenn die Mojang EULA in <code className="bg-neutral-900 px-1 py-0.5 rounded text-amber-300 font-mono">eula.txt</code> auf <code className="text-emerald-400">true</code> gesetzt wird.
              </p>
            </div>
          </div>
          <button
            onClick={handleAcceptEula}
            className="flex items-center gap-1.5 px-4 py-2 bg-emerald-600 hover:bg-emerald-500 text-white font-semibold rounded-lg shrink-0 cursor-pointer transition-colors shadow-sm shadow-emerald-600/30"
          >
            <Check className="w-3.5 h-3.5" />
            <span>EULA mit 1 Klick akzeptieren</span>
          </button>
        </div>
      )}

      {/* Main File Browser & In-Browser Editor */}
      <div className="bg-neutral-900 border border-neutral-800 rounded-xl overflow-hidden min-h-[580px] flex flex-col">
        {/* File Browser Header Bar */}
        <div className="p-3 bg-neutral-950 border-b border-neutral-800 flex flex-wrap items-center justify-between gap-2 text-xs">
          {/* Breadcrumbs Navigation */}
          <div className="flex items-center gap-1 overflow-x-auto py-1">
            <button
              onClick={() => { setCurrentPath('/'); setSelectedFile(null); }}
              className={`px-2 py-1 rounded transition-colors font-mono cursor-pointer ${
                currentPath === '/' ? 'bg-neutral-800 text-emerald-400 font-bold' : 'text-neutral-400 hover:text-neutral-200'
              }`}
            >
              /root
            </button>
            {currentPath !== '/' && currentPath.split('/').filter(Boolean).map((segment, idx, arr) => {
              const subPath = '/' + arr.slice(0, idx + 1).join('/');
              const isLast = idx === arr.length - 1;
              return (
                <React.Fragment key={subPath}>
                  <ChevronRight className="w-3 h-3 text-neutral-600 shrink-0" />
                  <button
                    onClick={() => { setCurrentPath(subPath); setSelectedFile(null); }}
                    className={`px-2 py-1 rounded transition-colors font-mono cursor-pointer ${
                      isLast ? 'bg-neutral-800 text-emerald-400 font-bold' : 'text-neutral-400 hover:text-neutral-200'
                    }`}
                  >
                    {segment}
                  </button>
                </React.Fragment>
              );
            })}
          </div>

          {/* Action Buttons */}
          <div className="flex items-center gap-2">
            <div className="relative">
              <Search className="w-3.5 h-3.5 text-neutral-500 absolute left-2.5 top-1/2 -translate-y-1/2" />
              <input
                type="text"
                placeholder="Dateien filtern..."
                value={searchFilter}
                onChange={(e) => setSearchFilter(e.target.value)}
                className="pl-8 pr-3 py-1 bg-neutral-900 border border-neutral-800 rounded-lg text-xs text-neutral-200 placeholder-neutral-500 focus:outline-none focus:border-neutral-700 w-36 sm:w-48"
              />
            </div>

            <button
              onClick={() => setIsNewFileModalOpen(true)}
              className="flex items-center gap-1.5 px-3 py-1 bg-neutral-900 hover:bg-neutral-800 text-neutral-300 rounded-lg border border-neutral-800 cursor-pointer transition-colors"
            >
              <FilePlus className="w-3.5 h-3.5 text-emerald-400" />
              <span>Neu</span>
            </button>

            <button
              onClick={handleSimulateUpload}
              disabled={isUploading}
              className="flex items-center gap-1.5 px-3 py-1 bg-emerald-950 hover:bg-emerald-900 text-emerald-300 rounded-lg border border-emerald-800/80 cursor-pointer transition-colors disabled:opacity-50"
            >
              <Upload className="w-3.5 h-3.5" />
              <span>{isUploading ? `Upload (${uploadProgress}%)` : 'Hochladen'}</span>
            </button>
          </div>
        </div>

        {/* Content Area: Split File Tree / In-Browser Editor */}
        <div className="grid grid-cols-1 lg:grid-cols-12 flex-1">
          {/* File List Column */}
          <div className={`p-3 bg-neutral-950/60 border-r border-neutral-800 flex flex-col justify-between ${
            selectedFile ? 'lg:col-span-5' : 'lg:col-span-12'
          }`}>
            <div className="space-y-1">
              {currentPath !== '/' && (
                <button
                  onClick={() => {
                    const parent = currentPath.substring(0, currentPath.lastIndexOf('/')) || '/';
                    setCurrentPath(parent);
                  }}
                  className="w-full flex items-center gap-2.5 p-2 rounded-lg text-xs text-neutral-400 hover:text-neutral-200 hover:bg-neutral-900 transition-colors cursor-pointer"
                >
                  <ArrowLeft className="w-4 h-4 text-neutral-500" />
                  <span className="font-mono">.. (Übergeordnetes Verzeichnis)</span>
                </button>
              )}

              {currentDirectoryFiles.length === 0 ? (
                <div className="text-center py-12 text-xs text-neutral-500">
                  <Folder className="w-8 h-8 mx-auto mb-2 opacity-30" />
                  Keine Dateien in diesem Ordner vorhanden
                </div>
              ) : (
                currentDirectoryFiles.map(file => {
                  const isSelected = selectedFile?.path === file.path;
                  return (
                    <div
                      key={file.path}
                      onClick={() => handleOpenFile(file)}
                      className={`group flex items-center justify-between p-2 rounded-lg text-xs cursor-pointer transition-colors border ${
                        isSelected 
                          ? 'bg-neutral-800/90 border-neutral-700 text-neutral-100' 
                          : 'border-transparent hover:bg-neutral-900 hover:border-neutral-800 text-neutral-300'
                      }`}
                    >
                      <div className="flex items-center gap-2.5 min-w-0">
                        {file.type === 'directory' ? (
                          <Folder className="w-4 h-4 text-amber-400 shrink-0 fill-amber-400/20" />
                        ) : file.name.endsWith('.jar') ? (
                          <Archive className="w-4 h-4 text-purple-400 shrink-0" />
                        ) : (
                          <FileCode className="w-4 h-4 text-sky-400 shrink-0" />
                        )}
                        <span className="font-mono truncate">{file.name}</span>
                        {file.name === 'eula.txt' && file.content?.includes('eula=false') && (
                          <span className="px-1.5 py-0.2 text-[10px] font-bold bg-rose-950 text-rose-400 rounded border border-rose-800">
                            EULA prüfen!
                          </span>
                        )}
                      </div>

                      <div className="flex items-center gap-3 shrink-0 text-neutral-500 text-[11px]">
                        <span>{formatFileSize(file.sizeBytes)}</span>
                        <span className="hidden sm:inline">{file.lastModified}</span>
                        <button
                          onClick={(e) => { e.stopPropagation(); handleDeleteFile(file.path); }}
                          className="opacity-0 group-hover:opacity-100 p-1 hover:text-rose-400 transition-opacity"
                          title="Löschen"
                        >
                          <Trash2 className="w-3.5 h-3.5" />
                        </button>
                      </div>
                    </div>
                  );
                })
              )}
            </div>

            {/* Storage Info Footer */}
            <div className="mt-4 pt-3 border-t border-neutral-800/80 flex items-center justify-between text-xs text-neutral-500">
              <span className="flex items-center gap-1.5">
                <HardDrive className="w-3.5 h-3.5 text-neutral-400" />
                <span>Speicherplatz: {(server.diskUsageMb / 1024).toFixed(2)} GB belegt</span>
              </span>
              <span>{files.length} Elemente</span>
            </div>
          </div>

          {/* In-Browser File Editor Column */}
          {selectedFile ? (
            <div className="lg:col-span-7 flex flex-col bg-neutral-900">
              {/* Editor Header */}
              <div className="p-3 bg-neutral-950 border-b border-neutral-800 flex items-center justify-between text-xs">
                <div className="flex items-center gap-2">
                  <FileCode className="w-4 h-4 text-sky-400" />
                  <span className="font-mono font-semibold text-neutral-200">{selectedFile.name}</span>
                  <span className="text-neutral-500 text-[11px]">({formatFileSize(selectedFile.sizeBytes)})</span>
                </div>

                <div className="flex items-center gap-2">
                  {selectedFile.isEditable ? (
                    <button
                      onClick={handleSaveFile}
                      className="flex items-center gap-1.5 px-3 py-1.5 bg-emerald-600 hover:bg-emerald-500 text-white rounded-lg font-medium cursor-pointer transition-colors shadow-sm shadow-emerald-600/30"
                    >
                      {saveSuccess ? <Check className="w-3.5 h-3.5" /> : <Save className="w-3.5 h-3.5" />}
                      <span>{saveSuccess ? 'Gespeichert!' : 'Speichern'}</span>
                    </button>
                  ) : (
                    <span className="text-neutral-500 italic">Binärdatei (Nur Leseansicht)</span>
                  )}
                  <button
                    onClick={() => setSelectedFile(null)}
                    className="p-1.5 rounded-lg hover:bg-neutral-800 text-neutral-400 hover:text-neutral-200 cursor-pointer"
                    title="Editor schließen"
                  >
                    <ArrowLeft className="w-3.5 h-3.5" />
                  </button>
                </div>
              </div>

              {/* Textarea Editor */}
              <div className="flex-1 p-3 flex flex-col">
                <textarea
                  value={editorContent}
                  onChange={(e) => setEditorContent(e.target.value)}
                  disabled={!selectedFile.isEditable}
                  className="w-full flex-1 bg-neutral-950 border border-neutral-800 rounded-lg p-3 font-mono text-xs text-neutral-200 focus:outline-none focus:border-neutral-700 resize-none leading-relaxed selection:bg-emerald-900"
                  spellCheck={false}
                  rows={20}
                />
              </div>

              {/* Editor Status Bar */}
              <div className="px-4 py-2 bg-neutral-950 border-t border-neutral-800 flex items-center justify-between text-[11px] text-neutral-500 font-mono">
                <span>Zeilen: {editorContent.split('\n').length} | Zeichen: {editorContent.length}</span>
                <span>UTF-8 | LF</span>
              </div>
            </div>
          ) : (
            <div className="hidden lg:flex lg:col-span-7 flex-col items-center justify-center p-12 text-center text-xs text-neutral-500 bg-neutral-900/50">
              <FileText className="w-10 h-10 mb-3 opacity-20" />
              <p className="font-medium text-neutral-400">Keine Datei ausgewählt</p>
              <p className="mt-1 text-neutral-500 max-w-xs">
                Klicke links auf eine Datei (z. B. <code className="font-mono text-emerald-400">server.properties</code> oder <code className="font-mono text-emerald-400">eula.txt</code>), um sie direkt im Browser zu bearbeiten.
              </p>
            </div>
          )}
        </div>
      </div>

      {/* Modal: Create File / Directory */}
      {isNewFileModalOpen && (
        <div className="fixed inset-0 z-50 bg-black/70 backdrop-blur-xs flex items-center justify-center p-4">
          <div className="bg-neutral-900 border border-neutral-800 rounded-xl p-5 max-w-md w-full shadow-2xl">
            <h3 className="text-sm font-bold text-neutral-100 mb-2 flex items-center gap-2">
              <Plus className="w-4 h-4 text-emerald-400" />
              Neue Datei oder neuen Ordner erstellen
            </h3>
            <p className="text-xs text-neutral-400 mb-4">
              Für Ordner hänge einfach einen Schrägstrich an (z. B. <code className="font-mono text-emerald-400">mods/</code> oder <code className="font-mono text-emerald-400">plugins/</code>).
            </p>

            <div className="space-y-3">
              <div>
                <label className="text-xs text-neutral-400 block mb-1">Name der Datei oder des Ordners</label>
                <input
                  type="text"
                  placeholder="z.B. custom-config.yml oder logs/"
                  value={newFileName}
                  onChange={(e) => setNewFileName(e.target.value)}
                  className="w-full px-3 py-2 bg-neutral-950 border border-neutral-800 rounded-lg text-xs text-neutral-200 focus:outline-none focus:border-neutral-700"
                  autoFocus
                />
              </div>

              <div className="flex justify-end gap-2 pt-2">
                <button
                  onClick={() => setIsNewFileModalOpen(false)}
                  className="px-3 py-1.5 bg-neutral-800 hover:bg-neutral-700 text-neutral-300 rounded-lg text-xs cursor-pointer"
                >
                  Abbrechen
                </button>
                <button
                  onClick={handleCreateFile}
                  disabled={!newFileName.trim()}
                  className="px-4 py-1.5 bg-emerald-600 hover:bg-emerald-500 text-white rounded-lg text-xs font-semibold cursor-pointer disabled:opacity-50"
                >
                  Erstellen
                </button>
              </div>
            </div>
          </div>
        </div>
      )}

      {/* Delete File/Folder Confirmation Modal */}
      {fileToDelete && (
        <div className="fixed inset-0 z-50 bg-black/80 backdrop-blur-sm flex items-center justify-center p-4">
          <div className="bg-neutral-900 border border-rose-900/60 rounded-xl max-w-sm w-full p-5 space-y-4 shadow-2xl">
            <div className="flex items-center gap-3">
              <div className="w-9 h-9 rounded-lg bg-rose-950 border border-rose-800 flex items-center justify-center text-rose-400 shrink-0">
                <Trash2 className="w-4 h-4" />
              </div>
              <div>
                <h3 className="font-bold text-neutral-100 text-sm">Datei/Ordner löschen?</h3>
                <p className="text-[11px] text-neutral-400">Diese Datei wird unwiderruflich entfernt.</p>
              </div>
            </div>

            <div className="p-2.5 bg-neutral-950 rounded-lg border border-neutral-800 font-mono text-xs text-rose-300 truncate">
              {fileToDelete}
            </div>

            <div className="flex justify-end gap-2 pt-1 text-xs">
              <button
                onClick={() => setFileToDelete(null)}
                className="px-3 py-1.5 bg-neutral-800 hover:bg-neutral-700 text-neutral-300 rounded-lg cursor-pointer"
              >
                Abbrechen
              </button>
              <button
                onClick={handleConfirmDeleteFile}
                className="px-3.5 py-1.5 bg-rose-600 hover:bg-rose-500 text-white font-semibold rounded-lg cursor-pointer transition-colors"
              >
                Löschen
              </button>
            </div>
          </div>
        </div>
      )}
    </div>
  );
};
